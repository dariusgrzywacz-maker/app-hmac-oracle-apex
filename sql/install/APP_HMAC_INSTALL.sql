create or replace editionable package app_hmac_admin authid definer as
    /**
     * Pakiet administracyjny do rotacji kluczy HMAC i zarządzania okresem ich
     * weryfikacji. Operacje są audytowane w APP_HMAC_ADMIN_LOG.
     *
     * Bezpieczeństwo:
     *   * pakiet działa z AUTHID DEFINER;
     *   * EXECUTE należy nadac wylacznie administratorom lub kontrolowanemu jobowi;
     *   * nie należy nadawać aplikacji bezpośredniego dostępu do APP_HMAC_KEYS
     *     ani APP_HMAC_ADMIN_LOG.
     */
    /**
     * Rotuje aktywny klucz podpisujący: wyłącza jego podpisywanie i tworzy
     * nowy klucz 256-bitowy. Poprzedni klucz pozostaje dostępny do weryfikacji
     * do czasu jego administracyjnego wyłączenia.
     *
     * @param p_new_key_id Identyfikator nowego klucza; po trim i upper musi
     *                     odpowiadać formatowi [A-Z0-9_], maksymalnie 30 znaków.
     * @raises -20980 Nieprawidłowy identyfikator klucza.
     * @raises -20981 Klucz o podanym identyfikatorze już istnieje.
     */
    procedure rotate_key(p_new_key_id in varchar2);

    /**
     * Wyłącza weryfikację kluczy, które nie podpisują już nowych danych i
     * przekroczyły wskazany okres przejściowy. Minimalny okres uwzględnia
     * najdłuższy TTL włączonej akcji oraz 60 sekund tolerancji.
     *
     * @param p_grace_hours Okres przejściowy w pełnych godzinach, od 1 do 8760;
     *                      domyślnie 25 godzin.
     * @raises -20982 Okres przejściowy jest nieprawidłowy.
     * @raises -20983 Okres przejściowy jest krótszy od wymaganego minimum.
     */
    procedure disable_expired_verification_keys(p_grace_hours in number default 25);
end app_hmac_admin;
/

create or replace editionable package body app_hmac_admin as
    c_key_bytes constant pls_integer:=32;
    c_ttl_tolerance_secs constant pls_integer:=60;

    procedure write_log(p_operation varchar2,p_old_key varchar2,p_new_key varchar2,p_grace number,p_rows number,p_status varchar2,p_code number default null,p_message varchar2 default null) is
        pragma autonomous_transaction;
    begin
        insert into app_hmac_admin_log(operation_name,old_key_id,new_key_id,grace_hours,affected_rows,operation_status,error_code,error_message,
            session_user_name,current_user_name,client_identifier,module_name,action_name)
        values(p_operation,p_old_key,p_new_key,p_grace,p_rows,p_status,p_code,substr(p_message,1,4000),
            sys_context('USERENV','SESSION_USER'),sys_context('USERENV','CURRENT_USER'),sys_context('USERENV','CLIENT_IDENTIFIER'),
            sys_context('USERENV','MODULE'),sys_context('USERENV','ACTION'));
        commit;
    exception when others then rollback;
    end;

    procedure rotate_key(p_new_key_id in varchar2) is
        l_new app_hmac_keys.key_id%type:=upper(trim(p_new_key_id)); l_old app_hmac_keys.key_id%type; l_rows pls_integer:=0;
    begin
        savepoint app_hmac_rotate_sp;
        if l_new is null or not regexp_like(l_new,'^[A-Z0-9_]{1,30}$','c') then raise_application_error(-20980,'Nieprawidłowy identyfikator klucza.'); end if;
        begin select key_id into l_old from app_hmac_keys where sign_enabled='Y' for update; exception when no_data_found then l_old:=null; end;
        update app_hmac_keys set sign_enabled='N',sign_disabled_at=systimestamp,updated_at=systimestamp,
            updated_by=sys_context('USERENV','SESSION_USER') where sign_enabled='Y';
        l_rows:=sql%rowcount;
        insert into app_hmac_keys(key_id,secret_value,sign_enabled,verify_enabled,created_by)
        values(l_new,dbms_crypto.randombytes(c_key_bytes),'Y','Y',sys_context('USERENV','SESSION_USER'));
        write_log('ROTATE_KEY',l_old,l_new,null,l_rows+1,'SUCCESS');
    exception
        when dup_val_on_index then rollback to app_hmac_rotate_sp; write_log('ROTATE_KEY',l_old,l_new,null,0,'ERROR',-20981,'Klucz juz istnieje.'); raise_application_error(-20981,'Klucz o podanym identyfikatorze już istnieje.');
        when others then rollback to app_hmac_rotate_sp; write_log('ROTATE_KEY',l_old,l_new,null,0,'ERROR',sqlcode,sqlerrm); raise;
    end;

    procedure disable_expired_verification_keys(p_grace_hours in number default 25) is
        l_required pls_integer; l_rows pls_integer;
    begin
        savepoint app_hmac_disable_sp;
        if p_grace_hours is null or p_grace_hours<>trunc(p_grace_hours) or p_grace_hours not between 1 and 8760 then
            raise_application_error(-20982,'Okres przejściowy musi być pełną liczbą godzin od 1 do 8760.');
        end if;
        select greatest(1,ceil((nvl(max(ttl_seconds),0)+c_ttl_tolerance_secs)/3600)) into l_required
          from app_hmac_actions where enabled='Y' and expiration_mode='TTL';
        if p_grace_hours<l_required then raise_application_error(-20983,'Okres przejściowy nie może byc krótszy niż '||l_required||' godz.'); end if;
        update app_hmac_keys set verify_enabled='N',valid_to=systimestamp,updated_at=systimestamp,
            updated_by=sys_context('USERENV','SESSION_USER')
         where sign_enabled='N' and verify_enabled='Y' and sign_disabled_at is not null
           and valid_from<systimestamp and sign_disabled_at<systimestamp-numtodsinterval(p_grace_hours,'HOUR');
        l_rows:=sql%rowcount;
        write_log('DISABLE_VERIFICATION_KEYS',null,null,p_grace_hours,l_rows,'SUCCESS');
    exception when others then
        rollback to app_hmac_disable_sp;
        write_log('DISABLE_VERIFICATION_KEYS',null,null,p_grace_hours,0,'ERROR',sqlcode,sqlerrm);
        raise;
    end;
end app_hmac_admin;

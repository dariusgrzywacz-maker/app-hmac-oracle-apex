create or replace editionable package app_hmac authid definer as
--------------------------------------------------------------------------------
--  APP_HMAC
--
--  Autor:       Dariusz Grzywacz
--  Utworzono:   2026-11-12
--  Schemat:     XXXX
--  Cel:         Ochrona integralności parametrów przekazywanych w Oracle APEX
--               przy uzyciu HMAC-SHA256.
--
--  Wersja:      APP_HMAC_V4
--  Tryby:
--    SESSION    Podpis jest związany z workspace, APP_ID, APP_USER i APP_SESSION.
--               Jest ważny do końca sesji APEX, wycofania klucza albo zmiany
--               konfiguracji operacji.
--    TTL        Jak SESSION, dodatkowo zawiera termin wygaśnięcia zapisany w UTC.
--
--  Bezpieczeństwo:
--    * pakiet działa z AUTHID DEFINER;
--    * sekret HMAC nie jest zwracany przez publiczne API;
--    * nazwa operacji musi być jawnie skonfigurowana i włączona;
--    * HMAC nie zastępuje Authorization Scheme ani autoryzacji biznesowej
--      wykonywanej bezpośrednio przed operacja DML;
--    * p_params powinno zawierać wszystkie dane mające wpływ na operacje.
--
--  Zależności:
--    APP_HMAC_KEYS, APP_HMAC_ACTIONS, DBMS_CRYPTO, UTL_I18N, Oracle APEX.
--------------------------------------------------------------------------------

    /**
     * Tworzy podpis HMAC dla operacji i przekazanych parametrów.
     *
     * @param p_action Nazwa operacji z APP_HMAC_ACTIONS; format [A-Z0-9_],
     *                 maksymalnie 100 znaków.
     * @param p_params Kanoniczna reprezentacja podpisywanych parametrów;
     *                 maksymalnie 4000 bajtow.
     * @return Podpis w formacie KEY_ID.MODE.EXPIRES_AT.HMAC_HEX.
     * @raises -20990 Brak aktywnego klucza podpisujacego.
     * @raises -20991 Wiele aktywnych kluczy podpisujacych.
     * @raises -20992 Nieprawidlowa nazwa operacji.
     * @raises -20995 Przekroczony limit parametrow.
     * @raises -20996 Operacja nie jest dozwolona.
     * @raises -20997 Nieprawidlowy klucz HMAC.
     */
    function sign(p_action in varchar2, p_params in varchar2) return varchar2;

    /**
     * Weryfikuje podpis HMAC w kontekście bieżącej sesji APEX.
     *
     * @param p_action    Nazwa operacji użyta podczas podpisywania.
     * @param p_params    Dokładnie ta sama kanoniczna reprezentacja parametrów.
     * @param p_signature Podpis zwrocony przez SIGN.
     * @return TRUE, gdy podpis jest poprawny i nadal ważny; w przeciwnym razie
     *         FALSE. łędna konfiguracja operacji lub wejścia może zgłosić
     *         wyjątek aplikacyjny.
     */
    function verify(p_action in varchar2, p_params in varchar2, p_signature in varchar2) return boolean;

    /**
     * Weryfikuje podpis i przerywa wykonanie, jeśli podpis jest nieważny.
     *
     * @param p_action    Nazwa operacji użyta podczas podpisywania.
     * @param p_params    Dokładnie ta sama kanoniczna reprezentacja parametrów.
     * @param p_signature Podpis zwrocony przez SIGN.
     * @raises -20993 Podpis jest nieprawidlowy, wygasl lub zostal wycofany.
     */
    procedure assert_valid(p_action in varchar2, p_params in varchar2, p_signature in varchar2);

    /**
     * Tworzy podpis dla pojedynczego identyfikatora. Identyfikator jest
     * kodowany do wewnetrznego formatu ID=<dlugosc>:<wartosc>.
     *
     * @param p_action Nazwa operacji z APP_HMAC_ACTIONS.
     * @param p_id     Identyfikator chronionego rekordu lub obiektu.
     * @return Podpis zgodny z formatem funkcji SIGN.
     */
    function sign_id(p_action in varchar2, p_id in varchar2) return varchar2;

    /**
     * Weryfikuje podpis utworzony przez SIGN_ID.
     *
     * @param p_action    Nazwa operacji użyta podczas podpisywania.
     * @param p_id        Identyfikator użyty podczas podpisywania.
     * @param p_signature Podpis zwrocony przez SIGN_ID.
     * @return TRUE, gdy podpis jest poprawny i nadal wazny; w przeciwnym razie
     *         FALSE.
     */
    function verify_id(p_action in varchar2, p_id in varchar2, p_signature in varchar2) return boolean;

    /**
     * Weryfikuje podpis pojedynczego identyfikatora i przerywa wykonanie,
     * jeśli podpis jest nieważny.
     *
     * @param p_action    Nazwa operacji użyta podczas podpisywania.
     * @param p_id        Identyfikator użyty podczas podpisywania.
     * @param p_signature Podpis zwrocony przez SIGN_ID.
     * @raises -20993 Podpis jest nieprawidłowy, wygasł lub został wycofany.
     */
    procedure assert_valid_id(p_action in varchar2, p_id in varchar2, p_signature in varchar2);
end app_hmac;
/

create or replace editionable package body app_hmac as
    c_payload_version constant varchar2(30) := 'APP_HMAC_V4';
    c_max_params_bytes constant pls_integer := 4000;
    c_hmac_hex_length constant pls_integer := 64;
    c_ttl_tolerance_secs constant pls_integer := 60;
    subtype t_key_id is app_hmac_keys.key_id%type;
    subtype t_mode is app_hmac_actions.expiration_mode%type;

    function encode_value(p_value in varchar2) return varchar2 is
    begin
        if p_value is null then return '-1:'; end if;
        return lengthb(p_value)||':'||p_value;
    end;

    function build_id_params(p_id in varchar2) return varchar2 is
    begin return 'ID='||encode_value(p_id); end;

    procedure validate_input(p_action in varchar2, p_params in varchar2) is
    begin
        if p_action is null or not regexp_like(p_action,'^[A-Z0-9_]{1,100}$','c') then
            raise_application_error(-20992,'Nieprawidłowa nazwa operacji HMAC.');
        end if;
        if lengthb(p_params) > c_max_params_bytes then
            raise_application_error(-20995,'Parametry HMAC przekraczają 4000 bajtów.');
        end if;
    end;

    procedure get_action_config(p_action in varchar2, p_mode out t_mode, p_ttl_seconds out number) is
    begin
        select expiration_mode, ttl_seconds into p_mode, p_ttl_seconds
          from app_hmac_actions where action_name=p_action and enabled='Y';
    exception when no_data_found then
        raise_application_error(-20996,'Operacja HMAC nie jest dozwolona.');
    end;

    procedure get_signing_key(p_key_id out t_key_id, p_secret out raw) is
    begin
        select key_id, secret_value into p_key_id, p_secret
          from app_hmac_keys
         where sign_enabled='Y' and verify_enabled='Y'
           and valid_from <= systimestamp and (valid_to is null or valid_to > systimestamp);
    exception
        when no_data_found then raise_application_error(-20990,'Nie skonfigurowano aktywnego klucza HMAC.');
        when too_many_rows then raise_application_error(-20991,'Istnieje wiele aktywnych kluczy podpisujących HMAC.');
    end;

    function get_verification_key(p_key_id in t_key_id) return raw is
        l_secret app_hmac_keys.secret_value%type;
    begin
        select secret_value into l_secret from app_hmac_keys
         where key_id=p_key_id and verify_enabled='Y'
           and valid_from <= systimestamp and (valid_to is null or valid_to > systimestamp);
        return l_secret;
    exception when no_data_found then return null;
    end;

    function build_payload(p_action in varchar2,p_params in varchar2,p_key_id in varchar2,p_mode in varchar2,p_expires_at in varchar2) return varchar2 is
    begin
        return c_payload_version||'|'||encode_value(to_char(apex_custom_auth.get_security_group_id))
          ||'|'||encode_value(to_char(apex_application.g_flow_id))
          ||'|'||encode_value(apex_application.g_user)
          ||'|'||encode_value(to_char(apex_application.g_instance))
          ||'|'||encode_value(p_key_id)||'|'||encode_value(p_mode)
          ||'|'||encode_value(p_expires_at)||'|'||encode_value(p_action)||'|'||encode_value(p_params);
    end;

    function calculate_hmac(p_payload in varchar2,p_secret in raw) return varchar2 is
        l_payload_raw raw(32767); l_result raw(32);
    begin
        if p_secret is null or utl_raw.length(p_secret)<>32 then
            raise_application_error(-20997,'Nieprawidłowy klucz HMAC.');
        end if;
        l_payload_raw:=utl_i18n.string_to_raw(p_payload,'AL32UTF8');
        l_result:=dbms_crypto.mac(src=>l_payload_raw,typ=>dbms_crypto.hmac_sh256,key=>p_secret);
        return lower(rawtohex(l_result));
    end;

    function secure_equals(p_left in varchar2,p_right in varchar2) return boolean is l_diff pls_integer:=0;
    begin
        if p_left is null or p_right is null or length(p_left)<>c_hmac_hex_length or length(p_right)<>c_hmac_hex_length then return false; end if;
        for i in 1..c_hmac_hex_length loop
            if substr(p_left,i,1)<>substr(p_right,i,1) then l_diff:=l_diff+1; end if;
        end loop;
        return l_diff=0;
    end;

    procedure parse_signature(p_signature in varchar2,p_key_id out t_key_id,p_mode out t_mode,p_expires_at out varchar2,p_mac out varchar2) is
        d1 pls_integer; d2 pls_integer; d3 pls_integer;
    begin
        if p_signature is null or not regexp_like(p_signature,'^[A-Z0-9_]{1,30}\.(SESSION|TTL)\.([0-9]{14}|NONE)\.[0-9a-f]{64}$','c') then raise value_error; end if;
        d1:=instr(p_signature,'.',1,1); d2:=instr(p_signature,'.',1,2); d3:=instr(p_signature,'.',1,3);
        p_key_id:=substr(p_signature,1,d1-1); p_mode:=substr(p_signature,d1+1,d2-d1-1);
        p_expires_at:=substr(p_signature,d2+1,d3-d2-1); p_mac:=substr(p_signature,d3+1);
        if (p_mode='SESSION' and p_expires_at<>'NONE') or (p_mode='TTL' and p_expires_at='NONE') then raise value_error; end if;
    end;

    function sign(p_action in varchar2,p_params in varchar2) return varchar2 is
        l_mode t_mode; l_ttl number; l_key_id t_key_id; l_secret raw(32); l_exp varchar2(14); l_mac varchar2(64);
    begin
        validate_input(p_action,p_params); get_action_config(p_action,l_mode,l_ttl); get_signing_key(l_key_id,l_secret);
        if l_mode='SESSION' then l_exp:='NONE'; else
            l_exp:=to_char(sys_extract_utc(systimestamp)+numtodsinterval(l_ttl,'SECOND'),'YYYYMMDDHH24MISS');
        end if;
        l_mac:=calculate_hmac(build_payload(p_action,p_params,l_key_id,l_mode,l_exp),l_secret);
        return l_key_id||'.'||l_mode||'.'||l_exp||'.'||l_mac;
    end;

    function verify(p_action in varchar2,p_params in varchar2,p_signature in varchar2) return boolean is
        l_cfg_mode t_mode; l_token_mode t_mode; l_ttl number; l_key_id t_key_id; l_exp varchar2(14);
        l_exp_ts timestamp; l_mac varchar2(64); l_expected varchar2(64); l_secret raw(32);
    begin
        if p_action is null or p_signature is null then return false; end if;
        validate_input(p_action,p_params); get_action_config(p_action,l_cfg_mode,l_ttl);
        begin parse_signature(p_signature,l_key_id,l_token_mode,l_exp,l_mac); exception when value_error then return false; end;
        if l_token_mode<>l_cfg_mode then return false; end if;
        if l_token_mode='TTL' then
            begin l_exp_ts:=to_timestamp(l_exp,'YYYYMMDDHH24MISS'); exception when value_error then return false; end;
            if l_exp_ts < sys_extract_utc(systimestamp) then return false; end if;
            if l_exp_ts > sys_extract_utc(systimestamp)+numtodsinterval(l_ttl+c_ttl_tolerance_secs,'SECOND') then return false; end if;
        end if;
        l_secret:=get_verification_key(l_key_id); if l_secret is null then return false; end if;
        l_expected:=calculate_hmac(build_payload(p_action,p_params,l_key_id,l_token_mode,l_exp),l_secret);
        return secure_equals(l_mac,l_expected);
    end;

    procedure assert_valid(p_action in varchar2,p_params in varchar2,p_signature in varchar2) is
    begin if not verify(p_action,p_params,p_signature) then raise_application_error(-20993,'Nieprawidłowy lub nieważny podpis zadania.'); end if; end;
    function sign_id(p_action in varchar2,p_id in varchar2) return varchar2 is begin return sign(p_action,build_id_params(p_id)); end;
    function verify_id(p_action in varchar2,p_id in varchar2,p_signature in varchar2) return boolean is begin return verify(p_action,build_id_params(p_id),p_signature); end;
    procedure assert_valid_id(p_action in varchar2,p_id in varchar2,p_signature in varchar2) is begin assert_valid(p_action,build_id_params(p_id),p_signature); end;
end app_hmac;
/


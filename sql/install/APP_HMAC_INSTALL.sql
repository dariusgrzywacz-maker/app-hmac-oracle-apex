create table app_hmac_keys (
    key_id             varchar2(30) not null,
    secret_value       raw(32) not null,
    sign_enabled       varchar2(1) default 'N' not null,
    verify_enabled     varchar2(1) default 'Y' not null,
    valid_from         timestamp with time zone default systimestamp not null,
    valid_to           timestamp with time zone,
    sign_disabled_at   timestamp with time zone,
    created_at         timestamp with time zone default systimestamp not null,
    created_by         varchar2(255) default sys_context('USERENV','SESSION_USER') not null,
    updated_at         timestamp with time zone,
    updated_by         varchar2(255),
    constraint app_hmac_keys_pk primary key (key_id),
    constraint app_hmac_keys_ck1 check (sign_enabled in ('Y','N')),
    constraint app_hmac_keys_ck2 check (verify_enabled in ('Y','N')),
    constraint app_hmac_keys_ck3 check (valid_to is null or valid_to > valid_from),
    constraint app_hmac_keys_ck4 check ((sign_enabled='Y' and sign_disabled_at is null) or sign_enabled='N'),
    constraint app_hmac_keys_ck5 check (regexp_like(key_id,'^[A-Z0-9_]{1,30}$','c'))
);
create unique index app_hmac_keys_uq_active_sign
    on app_hmac_keys (case when sign_enabled='Y' then 1 end);

create table app_hmac_actions (
    action_name       varchar2(100) not null,
    expiration_mode   varchar2(10) default 'SESSION' not null,
    ttl_seconds       number(10),
    enabled           varchar2(1) default 'Y' not null,
    description       varchar2(1000),
    created_at        timestamp with time zone default systimestamp not null,
    created_by        varchar2(255) default sys_context('USERENV','SESSION_USER') not null,
    updated_at        timestamp with time zone,
    updated_by        varchar2(255),
    constraint app_hmac_actions_pk primary key (action_name),
    constraint app_hmac_actions_ck1 check (enabled in ('Y','N')),
    constraint app_hmac_actions_ck2 check (expiration_mode in ('SESSION','TTL')),
    constraint app_hmac_actions_ck3 check (
        (expiration_mode='SESSION' and ttl_seconds is null) or
        (expiration_mode='TTL' and ttl_seconds between 30 and 86400)
    ),
    constraint app_hmac_actions_ck4 check (regexp_like(action_name,'^[A-Z0-9_]{1,100}$','c'))
);

